#!/usr/bin/env node
'use strict';

const fs = require('fs');
const path = require('path');

function directories(dir) {
  return fs.readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();
}
function fileNames(dir, suffix) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isFile() && entry.name.endsWith(suffix))
    .map((entry) => entry.name.slice(0, -suffix.length)).sort();
}
function frontmatter(text) {
  const match = /^---\r?\n([\s\S]*?)\r?\n---/.exec(text);
  if (!match) return {};
  const out = {};
  const lines = match[1].split(/\r?\n/);
  for (let idx = 0; idx < lines.length; idx += 1) {
    const line = lines[idx];
    const at = line.indexOf(':');
    if (at <= 0 || /^\s/.test(line)) continue;
    const key = line.slice(0, at).trim();
    const raw = line.slice(at + 1).trim();
    if (/^[>|][+-]?$/.test(raw)) {
      const block = [];
      while (idx + 1 < lines.length && !/^\S/.test(lines[idx + 1])) block.push(lines[idx += 1].trim());
      out[key] = raw[0] === '>' ? block.join(' ').replace(/\s+/g, ' ').trim() : block.join('\n').trimEnd();
    } else {
      out[key] = raw.replace(/^['"]|['"]$/g, '');
    }
  }
  return out;
}
function mcpToolNames(root) {
  const dir = path.join(root, 'mcp-server', 'src', 'tools');
  const names = new Set();
  for (const name of fs.readdirSync(dir).filter((entry) => entry.endsWith('.ts'))) {
    const text = fs.readFileSync(path.join(dir, name), 'utf8');
    for (const match of text.matchAll(/server\.(?:tool|registerTool)\(\s*["']([^"']+)["']/g)) names.add(match[1]);
  }
  return [...names].sort();
}
function catalog(rootArg) {
  const root = fs.realpathSync(path.resolve(rootArg || process.cwd()));
  const commandDir = path.join(root, '.claude', 'commands');
  const commandNames = new Set(fileNames(commandDir, '.md'));
  const copilotSkillNames = new Set(fileNames(path.join(root, 'setup', 'copilot-templates'), '.prompt.md'));
  const skills = directories(path.join(root, 'skills')).map((name) => {
    const file = path.join(root, 'skills', name, 'SKILL.md');
    if (!fs.existsSync(file)) return null;
    const meta = frontmatter(fs.readFileSync(file, 'utf8'));
    return {
      name,
      description: meta.description || '',
      claude_command: commandNames.has(name),
      copilot: copilotSkillNames.has(name),
      copilot_configured: meta.copilot === 'true',
      status: meta.deprecated === 'true' ? 'deprecated' : 'active',
      replacement: meta.replacement || null,
    };
  }).filter(Boolean);
  const agents = fileNames(path.join(root, '.claude', 'agents'), '.md');
  const hooks = fs.readdirSync(path.join(root, '.claude', 'hooks'), { withFileTypes: true })
    .filter((entry) => entry.isFile()).map((entry) => entry.name).sort();
  const mcpTools = mcpToolNames(root);
  return {
    schema: 'operational-surface-catalog/v1',
    generated: 'deterministic',
    counts: {
      skills: skills.length,
      commands: commandNames.size,
      agents: agents.length,
      agent_templates: fileNames(path.join(root, 'setup', 'agent-templates'), '.md').filter((name) => name !== 'README').length,
      copilot_agent_templates: fileNames(path.join(root, 'setup', 'copilot-agent-templates'), '.agent.md').length,
      hooks: hooks.length,
      hook_js: hooks.filter((name) => name.endsWith('.js')).length,
      mcp_tools: mcpTools.length,
    },
    skills,
    command_only: [...commandNames].filter((name) => !skills.some((skill) => skill.name === name)).sort(),
    skill_without_command: skills.filter((skill) => !skill.claude_command).map((skill) => skill.name),
    agents,
    hooks,
    mcp_tools: mcpTools,
  };
}
function markdown(data) {
  const lines = [
    '---',
    'scope: [agents, skills, commands, mcp]',
    'sources: [skills, .claude/commands, .claude/agents, .claude/hooks, mcp-server/src/tools]',
    'targets: [all]',
    'slug: operational-surface-catalog',
    'status: active',
    'layer: L0',
    'parent: agents-hub',
    'category: agents',
    'description: "Generated catalog of public skills, command adapters, agents, hooks, and MCP tools."',
    'version: 1',
    'last_updated: "2026-09-22"',
    'generated: true',
    '---', '', '# Operational Surface Catalog', '',
    '> Generated by `node scripts/tools/generate-operational-catalog.cjs`. Edit canonical sources, not this table.', '',
    `**Counts:** ${data.counts.skills} skills · ${data.counts.commands} Claude commands · ${data.counts.agents} agents (${data.counts.agent_templates} canonical templates, ${data.counts.copilot_agent_templates} Copilot adapters) · ${data.counts.hooks} hook files (${data.counts.hook_js} JavaScript) · ${data.counts.mcp_tools} MCP tools.`, '',
    '## Skills and command adapters', '',
    '| Skill | Status | Claude command | Copilot adapter | Description |',
    '|---|---|---:|---:|---|',
  ];
  for (const skill of data.skills) {
    const description = skill.description.replaceAll('|', '\\|').replace(/\s+/g, ' ').trim();
    lines.push(`| \`${skill.name}\` | ${skill.status} | ${skill.claude_command ? 'yes' : 'no'} | ${skill.copilot ? 'yes' : (skill.copilot_configured ? '**missing**' : 'no')} | ${description} |`);
  }
  lines.push('', '## Command-only compatibility adapters', '');
  lines.push(data.command_only.length ? data.command_only.map((name) => `- \`${name}\``).join('\n') : 'None.');
  lines.push('', '## Skills without a Claude command adapter', '');
  lines.push(data.skill_without_command.length ? data.skill_without_command.map((name) => `- \`${name}\``).join('\n') : 'None.');
  lines.push('', '## Agent templates', '', data.agents.map((name) => `- \`${name}\``).join('\n'));
  lines.push('', '## Hooks', '', data.hooks.map((name) => `- \`${name}\``).join('\n'));
  lines.push('', '## MCP tools', '');
  lines.push(data.mcp_tools.map((name) => `- \`${name}\``).join('\n'), '');
  lines.push('## Authority and migration rules', '',
    '- `skills/*/SKILL.md` is canonical for skill behavior; `.claude/commands` is an adapter surface.',
    '- An alias or deprecation must be explicit in skill frontmatter and retain a tested migration window.',
    '- Missing runtime adapters reduce availability; they never change the portable disk authority contract.',
    '- MCP names come from actual `server.tool`/`server.registerTool` registrations, not README prose.', '');
  return lines.join('\n');
}

if (require.main === module) {
  const root = process.argv[2] || process.cwd();
  const output = process.argv[3] || path.join(root, 'docs', 'agents', 'operational-surface-catalog.md');
  fs.writeFileSync(output, markdown(catalog(root)), 'utf8');
}

module.exports = { catalog, markdown, frontmatter, mcpToolNames };
